#!/usr/bin/env python3
"""Scan results/*/eval.json (+ faithfulness/summary.json, bias_variance/bias_variance.json where
present) and emit one Markdown table per experiment group. Usage:
  python scripts/aggregate_results.py --root results --out results/SUMMARY.md
"""
import argparse, glob, json, os
from collections import defaultdict


def load(path):
    with open(path) as f: return json.load(f)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default="results")
    ap.add_argument("--out", default="results/SUMMARY.md")
    a = ap.parse_args()

    rows = []
    for p in sorted(glob.glob(os.path.join(a.root, "*", "eval.json"))):
        rows.append((os.path.basename(os.path.dirname(p)), load(p)))

    lines = ["# FaithTS results summary (auto-generated by scripts/aggregate_results.py)", ""]
    if rows:
        cols = ["run", "dataset", "model", "MAE", "MSE", "CRPS", "Coverage80", "mean_gate", "NDCG@5"]
        lines.append("| " + " | ".join(cols) + " |")
        lines.append("|" + "---|" * len(cols))
        for name, r in rows:
            vals = [name] + [str(r.get(c, "")) for c in cols[1:]]
            vals = [f"{v:.4f}" if isinstance(v, float) else v for v in
                    [name] + [r.get(c, "") for c in cols[1:]]]
            lines.append("| " + " | ".join(map(str, vals)) + " |")
    lines.append("")

    for p in sorted(glob.glob(os.path.join(a.root, "*", "faithfulness", "summary.json"))):
        run = os.path.basename(os.path.dirname(os.path.dirname(p)))
        s = load(p)
        lines.append(f"## Faithfulness intervention benchmark -- {run}")
        for k, v in s.items():
            lines.append(f"- **{k}**: {v:.4f}" if isinstance(v, float) else f"- **{k}**: {v}")
        lines.append("")

    for p in sorted(glob.glob(os.path.join(a.root, "*", "bias_variance", "bias_variance.json"))):
        run = os.path.basename(os.path.dirname(os.path.dirname(p)))
        d = load(p)
        lines.append(f"## Bias-variance / conditional-shift sweep -- {run}")
        for key in ["adaptive", "fixed"]:
            if key not in d: continue
            lines.append(f"### {key}")
            lines.append("| frac | bias2 | variance | mse | mean_gate |")
            lines.append("|---|---|---|---|---|")
            for row in d[key]:
                lines.append(f"| {row['frac']} | {row['bias2']:.4f} | {row['variance']:.4f} | "
                            f"{row['mse']:.4f} | {row['mean_gate']:.3f} |")
        if "adaptive" in d and "fixed" in d and d["adaptive"] and d["fixed"]:
            m0a, m1a = d["adaptive"][0]["mse"], d["adaptive"][-1]["mse"]
            m0f, m1f = d["fixed"][0]["mse"], d["fixed"][-1]["mse"]
            lines.append(f"\n**Relative MSE degradation (frac={d['adaptive'][0]['frac']} -> "
                        f"{d['adaptive'][-1]['frac']}):** adaptive = {100*(m1a-m0a)/m0a:.1f}%, "
                        f"fixed = {100*(m1f-m0f)/m0f:.1f}%\n")
        lines.append("")

    text = "\n".join(lines)
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    with open(a.out, "w") as f: f.write(text)
    print(text)


if __name__ == "__main__":
    main()
